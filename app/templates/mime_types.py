"""
Defines standardized MIME types for drag and drop operations throughout the application.
"""

# MIME type for template names (single or multiple, newline-separated)
TEMPLATE_NAMES_MIME_TYPE = "application/x-forwardflow-template-names"

# MIME type to indicate multi-template selection drag
TEMPLATE_MULTI_DRAG_MIME_TYPE = "application/x-template-multi-drag"

# MIME type for template data in JSON format (for complex data structures)
TEMPLATE_JSON_MIME_TYPE = "application/x-template-json-data"

# MIME type for multi-selection data as JSON
TEMPLATE_MULTI_SELECTION_MIME_TYPE = "application/x-template-multi-selection" 